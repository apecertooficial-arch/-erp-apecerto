  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  funil_lead_id uuid NOT NULL REFERENCES public.f2_lead(id) ON DELETE CASCADE,
  inicio_em timestamptz NOT NULL,
  imovel text NOT NULL CHECK (char_length(btrim(imovel)) BETWEEN 2 AND 120),
  status text NOT NULL DEFAULT 'agendada' CHECK (status IN ('agendada','confirmada','realizada','cancelada','nao_compareceu')),
  observacao text NULL CHECK (observacao IS NULL OR char_length(observacao)<=500),
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_por uuid NULL
