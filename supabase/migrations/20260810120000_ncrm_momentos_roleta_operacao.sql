-- CRM Nova Era 3.1 — etapa != momento, roleta operacional e feedback de visita.
--
-- Decisões da operação (03/08/2026):
--   * quatro ETAPAS do funil: Novo, Tentando contato, Em atendimento, Pós-visita;
--   * dez MOMENTOS padronizados, cada um com uma ação e um prazo;
--   * fora do horário não existe aceite/rejeição: o lead continua atribuído;
--   * redistribuição dos 5 minutos só ocorre no horário oficial;
--   * D-API conectada, presença e feedback de visita são critérios objetivos;
--   * suspensão por produtividade nasce DORMENTE até existir base de medição.
--
-- Esta migration não envia WhatsApp, não cria proposta/venda e não migra carteira.
