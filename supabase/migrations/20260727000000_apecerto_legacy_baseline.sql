      end if;
     if v_negocio_id is not null and v_pipe is not distinct from public.f2_pipeline_id() then   perform public.f2_entrada_direta(v_negocio_id,     coalesce((select s.chave from pipeline_stages s                where s.id = coalesce(v_stage,(select stage_id from negocios where id=v_negocio_id))),'novo'));   insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)   values(p_auto,p_nome,p_bloco,'acao','ok',p_lead->>'nome',v_tel,     'Funil 2.0: card criado para o negocio #'||v_negocio_id); end if; elsif act_name='move-business-action' then
      if v_lead_id is null then insert into leads(nome,telefone,status) values(coalesce(p_lead->>'nome','Lead'),v_tel,'novo') returning id into v_lead_id; end if;
      if v_negocio_id is null then
        if v_pipe is not null then
          select id into v_exist from negocios where lead_id=v_lead_id and pipeline_id=v_pipe and status='aberto' order by id desc limit 1;
        else
          select id into v_exist from negocios where lead_id=v_lead_id and status='aberto' order by id desc limit 1;
