      end loop;
      if _pc_target is not null then cur := _pc_target;
      elsif _c_cnt=0 or _c_all then cur := b#>>'{options,trueNextBlockId}';
      else cur := b#>>'{options,falseNextBlockId}';
      end if;
      trace := trace || format(E'>> Condicao (%s de %s) -> %s\n', (case when _any_true then 'alguma' else 'nenhuma' end), _c_cnt, coalesce(nullif(cur,''),'fim'));

    elsif tipo='randomizer' then
      v_total := (select coalesce(sum(nullif(r->>'perc','')::numeric),0) from jsonb_array_elements(coalesce(b#>'{options,randomizers}','[]'::jsonb)) r);
      if v_total <= 0 then
        cur := b#>>'{options,randomizers,0,nextBlockId}'; trace := trace || E'>> Randomizador (1o ramo)\n';
      else
        v_pick := random()*v_total; v_acc := 0; cur := null;
        for r_el in select value from jsonb_array_elements(b#>'{options,randomizers}') as t(value) loop
          v_acc := v_acc + coalesce(nullif(r_el->>'perc','')::numeric,0);
          if v_pick <= v_acc then cur := r_el->>'nextBlockId'; exit; end if;
        end loop;
        if cur is null then cur := b#>>'{options,randomizers,0,nextBlockId}'; end if;
        trace := trace || E'>> Randomizador (sorteado)\n';
      end if;

    elsif tipo='distribution-simple' then
      -- Funil 2.0: distribui e PARA. Sem abordagem automatica, sem reter o
      -- lead esperando resposta. Quem manda a mensagem e o corretor, pelo
      -- celular, e a evidencia e o D-API. tambemNegocio e forcado TRUE:
      -- negocio sem corretor nao entra no Funil 2.0.
      select motor_roleta(p_auto_id, a_nome, cur, p_lead, v_lead_id, v_negocio_id,
        coalesce(b#>'{options,distribuicao,items}','[]'::jsonb),
        coalesce((b#>>'{options,distribuicao,onlineOnly}')::boolean, true),
        true,
        coalesce(b#>'{options,distribuicao,protecao}', '["venda","visita_agendada","visita_realizada"]'::jsonb)) into _dist_cor;
      if _dist_cor is null then
        trace:=trace||E'>> Distribuicao simples (ninguem disponivel)\n';
        cur:=b#>>'{options,errorNextBlockId}';
      else
        trace:=trace||E'>> Distribuicao simples\n';
        cur:=b#>>'{options,nextBlockId}';
      end if;

    elsif tipo='distribution' then
      select motor_roleta(p_auto_id, a_nome, cur, p_lead, v_lead_id, v_negocio_id,
        coalesce(b#>'{options,distribuicao,items}','[]'::jsonb),
        coalesce((b#>>'{options,distribuicao,onlineOnly}')::boolean, false),
        coalesce((b#>>'{options,distribuicao,tambemNegocio}')::boolean, false),
        coalesce(b#>'{options,distribuicao,protecao}', '["venda","visita_agendada","visita_realizada"]'::jsonb)) into _dist_cor;
      if _dist_cor is not null then
        perform motor_envia_abordagem(p_auto_id, a_nome, cur, p_lead, v_lead_id, _dist_cor,
          nullif(b#>>'{options,distribuicao,produtoId}','')::bigint,
          coalesce(b#>'{options,distribuicao,abordagemIds}','[]'::jsonb));
      end if;
      if coalesce(b#>>'{options,respondeuNextBlockId}','') <> '' or coalesce(b#>>'{options,naoRespondeuNextBlockId}','') <> '' then
        v_unit := lower(coalesce(b#>>'{options,distribuicao,respostaUnidade}','horas'));
        v_secs := coalesce(nullif(b#>>'{options,distribuicao,respostaValor}','')::numeric, 12);
        v_due := now() + (v_secs * (case when v_unit like 'seg%' then interval '1 second' when v_unit like 'min%' then interval '1 minute' when v_unit like 'dia%' then interval '1 day' else interval '1 hour' end));
        insert into motor_fila(automacao_id,bloco_id,lead,due_at) values(p_auto_id,'RESP:'||cur,p_lead,v_due);
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)
        values(p_auto_id,a_nome,cur,'espera','ok',p_lead->>'nome',v_tel,'Aguardando resposta ate '||to_char(v_due at time zone 'America/Sao_Paulo','DD/MM HH24:MI')||' - lead RETIDO no bloco; se responder antes, sai na hora pela saida Respondeu');
        trace:=trace||E'>> Distribuicao (lead retido aguardando resposta)\n';
        return trace||E'-- pausado (aguardando resposta do lead) --';
      end if;
      trace:=trace||E'>> Distribuicao\n'; cur:=b#>>'{options,nextBlockId}';

    elsif tipo='action' then
      _res := motor_acoes(p_auto_id, a_nome, cur, p_lead, coalesce(b#>'{options,actions}','[]'::jsonb), v_lead_id, v_negocio_id, p_depth);
      v_lead_id := nullif(_res->>'lead_id','')::bigint; v_negocio_id := nullif(_res->>'negocio_id','')::bigint;
      trace:=trace||E'>> Acoes\n'; cur:=b#>>'{options,nextBlockId}';

    elsif tipo='time' then
      v_unit := lower(coalesce(b#>>'{options,unidade}','minutos'));
      v_secs := coalesce( nullif(b#>>'{options,valor}','')::numeric, nullif(b#>>'{options,min}','')::numeric, 0 );
      v_due := now() + (v_secs * (case when v_unit like 'seg%' then interval '1 second' when v_unit like 'min%' then interval '1 minute' when v_unit like 'hor%' then interval '1 hour' when v_unit like 'dia%' then interval '1 day' else interval '1 minute' end));
      cur := b#>>'{options,nextBlockId}';
      if cur is not null and cur<>'' then
        insert into motor_fila(automacao_id,bloco_id,lead,due_at) values(p_auto_id,cur,p_lead,v_due);
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)
        values(p_auto_id,a_nome,cur,'espera','ok',p_lead->>'nome',v_tel,'Aguardando ate '||to_char(v_due at time zone 'America/Sao_Paulo','DD/MM HH24:MI')||' (retoma sozinho)');
        trace:=trace||format(E'>> Espera ate %s (na fila)\n',v_due);
      end if;
      return trace||E'-- pausado (espera) --';

    elsif tipo='chat' then
      corretor:=b#>>'{options,corretor}';
      select i.instancia_dapi,c.apikey,i.nome into inst_dapi,inst_key,inst_nome from instancias i join instancias_credenciais c on c.instancia_id=i.id where i.nome=b#>>'{options,instancia}' or i.instancia_dapi=b#>>'{options,instancia}' limit 1;
      if inst_dapi is null and corretor is not null then
        select i.instancia_dapi,c.apikey,i.nome into inst_dapi,inst_key,inst_nome from instancias i join instancias_credenciais c on c.instancia_id=i.id where i.nome ilike corretor||'%' limit 1;
      end if;
      if inst_dapi is null then
        select i.instancia_dapi,c.apikey,i.nome into inst_dapi,inst_key,inst_nome from instancias i join instancias_credenciais c on c.instancia_id=i.id order by i.id limit 1;
      end if;
      destino:=motor_fone_br(motor_subst(coalesce(b#>>'{options,destinatario}','{telefone}'),p_lead));
      for msg in select value from jsonb_array_elements(b#>'{options,messages}') as t(value) loop
        if msg->>'name'='send-text-message' then
          mtext:=motor_subst(msg#>>'{options,text}',p_lead);
          if length(coalesce(mtext,''))=0 then
            insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto_id,a_nome,cur,'mensagem','alerta',p_lead->>'nome',p_lead->>'telefone','Texto vazio - nao enviado');
          else
            begin
              select status,left(content,300) as content into resp from extensions.http(('POST','https://api.d-api.cloud/api/v1/messages/send/text',ARRAY[extensions.http_header('Authorization',inst_key)],'application/json',json_build_object('sessionId',inst_dapi,'to',destino,'text',mtext)::text)::extensions.http_request);
              st := case when resp.status in (200,201) then 'ok' else 'erro' end;
              insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto_id,a_nome,cur,'mensagem',st,p_lead->>'nome',destino,'Texto via '||coalesce(inst_nome,'?')||' [HTTP '||resp.status||'] '||left(coalesce(resp.content,''),140));
            exception when others then
              insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto_id,a_nome,cur,'mensagem','erro',p_lead->>'nome',destino,'Falha no envio (texto) via '||coalesce(inst_nome,'?')||': '||left(coalesce(SQLERRM,''),140));
            end;
          end if;
        elsif msg->>'name' in ('send-image-message','send-video-message') then
          _ep := case when msg->>'name'='send-image-message' then 'image' else 'video' end;
          _mlabel := case when _ep='image' then 'Imagem' else 'Video' end;
          _murl := motor_subst(coalesce(msg#>>'{options,url}',''),p_lead);
          _mcap := motor_subst(coalesce(msg#>>'{options,caption}',''),p_lead);
          if coalesce(_murl,'')='' then
            insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto_id,a_nome,cur,'mensagem','alerta',p_lead->>'nome',destino,_mlabel||' sem arquivo - nao enviado');
          else
            _body := jsonb_build_object('sessionId',inst_dapi,'to',destino,_ep,_murl);
            if coalesce(_mcap,'')<>'' then _body := _body || jsonb_build_object('caption',_mcap); end if;
            begin
              select status,left(content,300) as content into resp from extensions.http(('POST','https://api.d-api.cloud/api/v1/messages/send/'||_ep,ARRAY[extensions.http_header('Authorization',inst_key)],'application/json',_body::text)::extensions.http_request);
              st := case when resp.status in (200,201) then 'ok' else 'erro' end;
              insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto_id,a_nome,cur,'mensagem',st,p_lead->>'nome',destino,_mlabel||' via '||coalesce(inst_nome,'?')||' [HTTP '||resp.status||'] '||left(coalesce(resp.content,''),120));
            exception when others then
              insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto_id,a_nome,cur,'mensagem','erro',p_lead->>'nome',destino,_mlabel||' falhou via '||coalesce(inst_nome,'?')||': '||left(coalesce(SQLERRM,''),120));
            end;
          end if;
        else
          insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto_id,a_nome,cur,'mensagem','alerta',p_lead->>'nome',destino,(msg->>'name')||' (proxima fatia)');
        end if;
      end loop;
      trace:=trace||E'>> Mensagem\n'; cur:=b#>>'{options,nextBlockId}';

    elsif tipo='resposta' then
      v_unit := lower(coalesce(b#>>'{options,janelaUnidade}','horas'));
      v_secs := coalesce(nullif(b#>>'{options,janelaValor}','')::numeric, 12);
      v_due := now() + (v_secs * (case when v_unit like 'seg%' then interval '1 second' when v_unit like 'min%' then interval '1 minute' when v_unit like 'dia%' then interval '1 day' else interval '1 hour' end));
      insert into motor_fila(automacao_id,bloco_id,lead,due_at) values(p_auto_id,'RESP2:'||cur,p_lead,v_due);
      insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)
      values(p_auto_id,a_nome,cur,'espera','ok',p_lead->>'nome',v_tel,
        'Vendo se o lead responde ate '||to_char(v_due at time zone 'America/Sao_Paulo','DD/MM HH24:MI'));
      trace:=trace||'>> Mapeamento de resposta (aguardando)'||chr(10);
      return trace||'-- pausado (vendo se o lead responde) --';

    elsif tipo='api' then
      _murl := coalesce(nullif(b#>>'{options,url}',''), nullif(b#>>'{options,endpoint}',''),
                        nullif(b#>>'{options,uri}',''), nullif(b#>>'{options,api,url}',''),
                        nullif(b#>>'{options,request,url}',''));
      _ep   := upper(coalesce(nullif(b#>>'{options,method}',''), nullif(b#>>'{options,metodo}',''), 'POST'));
      _mcap := coalesce(nullif(b#>>'{options,authorization}',''), nullif(b#>>'{options,token}',''),
                        nullif(b#>>'{options,auth}',''), '');
      _body := coalesce(b#>'{options,body}', b#>'{options,corpo}', b#>'{options,payload}',
                        b#>'{options,json}', '{}'::jsonb);
      if coalesce(_murl,'') = '' then
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)
        values(p_auto_id,a_nome,cur,'api','alerta',p_lead->>'nome',v_tel,
          'Bloco de API sem endereco. Veio configurado assim: '||left(coalesce(b->>'options','(vazio)'),260));
      else
        _murl := motor_subst(_murl, p_lead);
        begin
          select status, left(content,300) as content into resp from extensions.http((
            _ep, _murl,
            (case when _mcap <> '' then ARRAY[extensions.http_header('Authorization', _mcap)]
                  else ARRAY[]::extensions.http_header[] end)
            || (case when coalesce(b#>>'{options,apikey}','') <> ''
                     then ARRAY[extensions.http_header('apikey', b#>>'{options,apikey}')]
                     else ARRAY[]::extensions.http_header[] end),
            'application/json',
            motor_subst(_body::text, p_lead))::extensions.http_request);
          st := case when resp.status between 200 and 299 then 'ok' else 'erro' end;
          insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)
          values(p_auto_id,a_nome,cur,'api',st,p_lead->>'nome',v_tel,
            _ep||' '||left(_murl,70)||' [HTTP '||resp.status||'] '||left(coalesce(resp.content,''),120));
        exception when others then
          insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)
          values(p_auto_id,a_nome,cur,'api','erro',p_lead->>'nome',v_tel,
            'Chamada falhou: '||left(coalesce(SQLERRM,''),140));
        end;
      end if;
      trace:=trace||'>> API'||chr(10); cur:=b#>>'{options,nextBlockId}';

    elsif tipo='ai-agent' then
      _res := motor_agente(p_auto_id, a_nome, cur, p_lead, v_lead_id,
                nullif(b#>>'{options,agenteId}','')::bigint,
                coalesce(b#>>'{options,funcao}',''));
      trace:=trace||'>> Agente'||chr(10); cur:=b#>>'{options,nextBlockId}';

    elsif tipo='send-approach' then
      _dist_cor := null;
      if v_lead_id is not null then select corretor_id into _dist_cor from leads where id=v_lead_id; end if;
      if _dist_cor is null then
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)
        values(p_auto_id,a_nome,cur,'mensagem','alerta',p_lead->>'nome',v_tel,'Enviar abordagem: lead ainda sem corretor responsavel - coloque um bloco de Distribuicao antes');
      else
        perform motor_envia_abordagem(p_auto_id, a_nome, cur, p_lead, v_lead_id, _dist_cor,
          nullif(b#>>'{options,produtoId}','')::bigint,
          coalesce(b#>'{options,abordagemIds}','[]'::jsonb));
      end if;
      trace:=trace||E'>> Enviar abordagem (instancia do corretor dono)\n'; cur:=b#>>'{options,nextBlockId}';

    else
      cur:=b#>>'{options,nextBlockId}';
    end if;
  end loop;
  return trace||E'-- fim --';
end; $function$

