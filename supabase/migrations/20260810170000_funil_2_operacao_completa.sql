CREATE INDEX f2_visita_status_inicio_idx ON public.f2_visita(status,inicio_em);

CREATE TABLE public.f2_negociacao (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  funil_lead_id uuid NOT NULL REFERENCES public.f2_lead(id) ON DELETE CASCADE,
  titulo text NOT NULL CHECK (char_length(btrim(titulo)) BETWEEN 2 AND 120),
  etapa text NOT NULL DEFAULT 'qualificacao' CHECK (etapa IN ('qualificacao','simulacao','proposta','documentacao','contrato','venda','perdida')),
  valor numeric(14,2) NULL CHECK (valor IS NULL OR valor>=0),
  observacao text NULL CHECK (observacao IS NULL OR char_length(observacao)<=500),
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_por uuid NULL
);
CREATE INDEX f2_negociacao_etapa_idx ON public.f2_negociacao(etapa,atualizado_em DESC);

CREATE TABLE public.f2_config_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo text NOT NULL CHECK (tipo IN ('etapa','momento','visita','negociacao','pesca')),
  chave text NOT NULL,
  acao text NOT NULL,
  antes jsonb NULL,
  depois jsonb NULL,
  criado_em timestamptz NOT NULL DEFAULT now(),
  criado_por uuid NULL
