  codigo text PRIMARY KEY CHECK (codigo ~ '^[a-z0-9_]{3,40}$'),
  ordem smallint NOT NULL UNIQUE CHECK (ordem BETWEEN 1 AND 50),
  rotulo text NOT NULL CHECK (char_length(btrim(rotulo)) BETWEEN 2 AND 60),
  ajuda text NOT NULL DEFAULT '',
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);

