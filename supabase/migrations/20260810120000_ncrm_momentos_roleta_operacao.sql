-- ---------------------------------------------------------------------------
-- 4. Meu Dia e Sara passam a consumir o mesmo contrato
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.ncrm_fila_trabalho_v4(
  p_filtro text DEFAULT 'agora',p_corretor bigint DEFAULT NULL,p_limite int DEFAULT 100
) RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_uid uuid:=auth.uid(); v_lim int:=LEAST(GREATEST(coalesce(p_limite,100),1),300);
        v_admin boolean; v_broker bigint; v_itens jsonb;
BEGIN
  IF v_uid IS NULL THEN RETURN jsonb_build_object('ok',false,'erro','nao_autenticado'); END IF;
  v_admin:=coalesce(public.can_manage_all(),false); v_broker:=public.current_broker_id();
  SELECT coalesce(jsonb_agg(item ORDER BY (item->>'prioridade')::int,
    (item->>'proxima_acao_em')::timestamptz NULLS LAST),'[]'::jsonb) INTO v_itens
  FROM (
    SELECT jsonb_build_object(
      'negocio_id',e.negocio_id,'lead_nome',l.nome,'etapa',e.etapa,'momento_codigo',e.momento_codigo,
      'temperatura',e.temperatura,'corretor_id',n.corretor_id,'corretor_nome',coalesce(u.nome,'—'),
      'proxima_acao_titulo',e.proxima_acao_titulo,'proxima_acao_em',e.proxima_acao_em,
      'respondeu',e.respondeu,'resposta_pendente',e.resposta_pendente,'tentativas_feitas',e.tentativas_feitas,
      'prioridade',CASE WHEN e.resposta_pendente THEN 1 WHEN e.etapa='novo' THEN 2
        WHEN e.proxima_acao_em<now() THEN 3
        WHEN (e.proxima_acao_em AT TIME ZONE 'America/Sao_Paulo')::date=(now() AT TIME ZONE 'America/Sao_Paulo')::date THEN 4 ELSE 5 END,
      'motivo',CASE WHEN e.resposta_pendente THEN 'Cliente respondeu — aguardando você'
        WHEN e.etapa='novo' THEN 'Lead novo — primeira abordagem'
        WHEN e.proxima_acao_em<now() THEN 'Ação atrasada' ELSE 'Ação programada' END,
      'espera_min',greatest(0,extract(epoch FROM(now()-coalesce(e.proxima_acao_em,e.ultima_interacao_em,now())))/60)::numeric(12,1),
      'conduta',public.ncrm_conduta_oficial_v4(e.etapa,e.momento_codigo,e.respondeu,
        e.resposta_pendente,e.tentativas_feitas,e.proxima_acao_em)
    ) item
    FROM public.ncrm_estado e
    JOIN public.negocios n ON n.id=e.negocio_id
    JOIN public.leads l ON l.id=n.lead_id
    LEFT JOIN public.corretores c ON c.id=n.corretor_id
    LEFT JOIN public.usuarios u ON u.id=c.usuario_id
    WHERE e.saida IS NULL
      AND (v_admin OR n.corretor_id=v_broker OR coalesce(public.manages_broker(n.corretor_id),false))
      AND (p_corretor IS NULL OR n.corretor_id=p_corretor)
      AND CASE coalesce(p_filtro,'agora')
        WHEN 'agora' THEN e.resposta_pendente OR e.etapa='novo' OR e.proxima_acao_em<=date_trunc('day',now() AT TIME ZONE 'America/Sao_Paulo') AT TIME ZONE 'America/Sao_Paulo'+interval '1 day'
        WHEN 'vencidos' THEN e.proxima_acao_em<now()
        WHEN 'hoje' THEN (e.proxima_acao_em AT TIME ZONE 'America/Sao_Paulo')::date=(now() AT TIME ZONE 'America/Sao_Paulo')::date
        WHEN 'proximos' THEN e.proxima_acao_em>date_trunc('day',now() AT TIME ZONE 'America/Sao_Paulo') AT TIME ZONE 'America/Sao_Paulo'+interval '1 day'
        WHEN 'respondeu' THEN e.respondeu
        WHEN 'sem_resposta' THEN NOT e.respondeu
        WHEN 'risco' THEN e.proxima_acao_em<now()-interval '24 hours'
        WHEN 'quente' THEN e.temperatura IN ('quente','negociando') ELSE false END
    ORDER BY CASE WHEN e.resposta_pendente THEN 1 WHEN e.etapa='novo' THEN 2 WHEN e.proxima_acao_em<now() THEN 3 ELSE 4 END,
      e.proxima_acao_em NULLS LAST LIMIT v_lim
  ) q;
  RETURN jsonb_build_object('ok',true,'itens',v_itens,'regra','motor_operacional_v4');
END $fn$;
REVOKE ALL ON FUNCTION public.ncrm_fila_trabalho_v4(text,bigint,int) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.ncrm_fila_trabalho_v4(text,bigint,int) TO authenticated;

CREATE OR REPLACE FUNCTION public.ncrm_sara_aplicar_proxima_acao(
  p_negocio_id bigint,p_analise_id bigint,p_acao_codigo text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_uid uuid:=auth.uid(); v_e public.ncrm_estado%ROWTYPE; v_a public.ncrm_sara_analise%ROWTYPE;
        v_cat public.ncrm_acao_padrao%ROWTYPE; v_m public.ncrm_momento_padrao%ROWTYPE;
        v_lead bigint; v_corretor bigint; v_prazo timestamptz;
BEGIN
  IF v_uid IS NULL THEN RETURN jsonb_build_object('ok',false,'erro','nao_autenticado'); END IF;
  IF ncrm_private.pode_operar_negocio(p_negocio_id) IS NOT TRUE THEN RETURN jsonb_build_object('ok',false,'erro','sem_permissao'); END IF;
  SELECT * INTO v_a FROM public.ncrm_sara_analise WHERE id=p_analise_id AND negocio_id=p_negocio_id;
  IF v_a.id IS NULL THEN RETURN jsonb_build_object('ok',false,'erro','analise_inexistente'); END IF;
  IF v_a.analisado_em<now()-interval '30 minutes' THEN RETURN jsonb_build_object('ok',false,'erro','analise_desatualizada'); END IF;
  IF coalesce(v_a.confianca,0)<.70 THEN RETURN jsonb_build_object('ok',false,'erro','revisao_humana','aplicado',false); END IF;
  SELECT * INTO v_cat FROM public.ncrm_acao_padrao WHERE codigo=p_acao_codigo AND ativa;
  SELECT * INTO v_m FROM public.ncrm_momento_padrao WHERE acao_codigo=p_acao_codigo AND ativo ORDER BY ordem LIMIT 1;
  IF v_cat.codigo IS NULL OR v_m.codigo IS NULL THEN RETURN jsonb_build_object('ok',false,'erro','acao_fora_do_catalogo'); END IF;
  SELECT * INTO v_e FROM public.ncrm_estado WHERE negocio_id=p_negocio_id FOR UPDATE;
  IF v_e.negocio_id IS NULL OR v_e.saida IS NOT NULL THEN RETURN jsonb_build_object('ok',false,'erro','estado_indisponivel'); END IF;
  IF v_e.etapa='novo' AND p_acao_codigo<>'PRIMEIRA_ABORDAGEM' THEN RETURN jsonb_build_object('ok',false,'erro','acao_incompativel_com_momento'); END IF;
  IF NOT v_e.respondeu AND v_e.etapa='tentando_contato' AND p_acao_codigo<>'ENVIAR_CADENCIA' THEN RETURN jsonb_build_object('ok',false,'erro','acao_incompativel_com_momento'); END IF;
  IF v_e.resposta_pendente AND p_acao_codigo<>'RESPONDER_E_QUALIFICAR' THEN RETURN jsonb_build_object('ok',false,'erro','cliente_aguardando_resposta'); END IF;
  v_prazo:=greatest(coalesce(v_a.prazo_sugerido,now()+make_interval(mins=>v_cat.sla_min)),now()+interval '1 minute');
  SELECT lead_id,corretor_id INTO v_lead,v_corretor FROM public.negocios WHERE id=p_negocio_id;
  UPDATE public.ncrm_estado SET etapa=v_m.etapa,momento_codigo=v_m.codigo,
    proxima_acao_tipo=v_cat.proxima_acao_tipo,proxima_acao_titulo=v_cat.rotulo,proxima_acao_em=v_prazo,
    versao=v_e.versao+1,atualizado_em=now(),atualizado_por=v_uid,origem_ultima='sara',proxima_acao_origem='sara'
  WHERE negocio_id=p_negocio_id AND versao=v_e.versao;
  IF NOT FOUND THEN RETURN jsonb_build_object('ok',false,'erro','conflito_versao'); END IF;
  INSERT INTO public.ncrm_evento(negocio_id,lead_id,corretor_id_no_evento,workflow_config_id,tipo,resultado,payload,
    origem,executado_por,idempotency_key,estado_versao_antes,estado_versao_apos)
  VALUES(p_negocio_id,v_lead,v_corretor,v_e.workflow_config_id,'classificacao_sara',p_acao_codigo,
    jsonb_build_object('analise_id',p_analise_id,'momento_codigo',v_m.codigo,'prazo',v_prazo),
    'sara',NULL,concat('sara:conduta:',p_analise_id),v_e.versao,v_e.versao+1)
  ON CONFLICT(idempotency_key) WHERE idempotency_key IS NOT NULL DO NOTHING;
  RETURN jsonb_build_object('ok',true,'aplicado',true,'etapa',v_m.etapa,'momento_codigo',v_m.codigo,
    'momento',v_m.rotulo,'acao_codigo',p_acao_codigo,'acao',v_cat.rotulo,'prazo',v_prazo,'versao',v_e.versao+1);
END $fn$;
