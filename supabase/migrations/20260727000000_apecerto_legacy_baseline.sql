          v_negocio_id := v_exist;
          update negocios set stage_id=coalesce(v_stage,stage_id), pipeline_id=coalesce(v_pipe,pipeline_id), ultima_movimentacao=now() where id=v_negocio_id;
          insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao',case when v_stage is null then 'alerta' else 'ok' end,p_lead->>'nome',v_tel,case when v_stage is null then 'Mover: etapa nao encontrada ('||coalesce(ao->>'etapa','?')||')' else 'Negocio #'||v_negocio_id||' movido para '||coalesce(ao->>'etapa','#'||v_stage) end);
        elsif v_pipe is null then
          insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','erro',p_lead->>'nome',v_tel,'Mover: lead sem negocio e sem pipeline');
        else
          insert into negocios(lead_id,pipeline_id,stage_id,status,ultima_movimentacao) values(v_lead_id,v_pipe,v_stage,'aberto',now()) returning id into v_negocio_id;
          insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','ok',p_lead->>'nome',v_tel,'Negocio #'||v_negocio_id||' criado em '||coalesce(ao->>'etapa','etapa'));
        end if;
      else
        update negocios set stage_id=coalesce(v_stage,stage_id), pipeline_id=coalesce(v_pipe,pipeline_id), ultima_movimentacao=now() where id=v_negocio_id;
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao',case when v_stage is null then 'alerta' else 'ok' end,p_lead->>'nome',v_tel,case when v_stage is null then 'Mover: etapa nao encontrada ('||coalesce(ao->>'etapa','?')||')' else 'Negocio #'||v_negocio_id||' movido para '||coalesce(ao->>'etapa','#'||v_stage) end);
      end if;
    elsif act_name in ('business-win-action','business-lose-action','business-restore-action') then
      if v_negocio_id is null then
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','alerta',p_lead->>'nome',v_tel,'Status negocio: lead sem negocio');
      else
        update negocios set status = case act_name when 'business-win-action' then 'ganho' when 'business-lose-action' then 'perdido' else 'aberto' end,
          motivo_perda = case when act_name='business-lose-action' then nullif(ao->>'motivo','') else motivo_perda end,
          ultima_movimentacao=now() where id=v_negocio_id;
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','ok',p_lead->>'nome',v_tel,'Negocio '||(case act_name when 'business-win-action' then 'ganho' when 'business-lose-action' then 'perdido' else 'restaurado' end));
      end if;
    elsif act_name='add-attendant-on-business-action' then
      if v_cor is null then
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','erro',p_lead->>'nome',v_tel,'Atribuir: corretor nao encontrado ('||coalesce(ao->>'corretor','?')||')');
      else
        if v_negocio_id is not null then update negocios set corretor_id=v_cor where id=v_negocio_id; end if;
        if v_lead_id is not null and v_tambem then update leads set corretor_id=v_cor where id=v_lead_id; end if;
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','ok',p_lead->>'nome',v_tel,'Corretor atribuido: '||coalesce(ao->>'corretor','#'||v_cor)||case when v_tambem then ' (negocio+lead)' else ' (negocio)' end);
      end if;
    elsif act_name='clean-attendant-on-business-action' then
      if v_negocio_id is not null then update negocios set corretor_id=null where id=v_negocio_id; end if;
      if v_lead_id is not null and v_tambem then update leads set corretor_id=null where id=v_lead_id; end if;
      insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','ok',p_lead->>'nome',v_tel,'Atendente removido'||case when v_tambem then ' (negocio+lead)' else ' (negocio)' end);
    elsif act_name='assign-lead-attendant-action' then
      if v_cor is null then
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','erro',p_lead->>'nome',v_tel,'Atendente lead: corretor nao encontrado ('||coalesce(ao->>'corretor','?')||')');
      elsif v_lead_id is not null then
        update leads set corretor_id=v_cor where id=v_lead_id;
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','ok',p_lead->>'nome',v_tel,'Atendente do lead: '||coalesce(ao->>'corretor','#'||v_cor));
      else
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','alerta',p_lead->>'nome',v_tel,'Atendente lead: lead inexistente');
      end if;
    elsif act_name='clean-lead-attendant-action' then
      if v_lead_id is not null then update leads set corretor_id=null where id=v_lead_id; end if;
      insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','ok',p_lead->>'nome',v_tel,'Atendente do lead removido');
    elsif act_name in ('add-tag-action','create-tags-action') then
      v_tag := public.motor_subst(coalesce(ao->>'tag',''), p_lead);
      if v_lead_id is null then
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','alerta',p_lead->>'nome',v_tel,'Tag: lead ainda nao existe');
      elsif v_tag='' then
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','alerta',p_lead->>'nome',v_tel,'Tag vazia');
      elsif not exists(select 1 from leads l, jsonb_array_elements(case when jsonb_typeof(l.tags)='array' then l.tags else '[]'::jsonb end) e where l.id=v_lead_id and lower(e->>'name')=lower(v_tag)) then
        update leads set tags = (case when jsonb_typeof(tags)='array' then tags else '[]'::jsonb end) || jsonb_build_object('id',gen_random_uuid()::text,'name',v_tag,'color','#FF7000','createdAt',now(),'description','') where id=v_lead_id;
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','ok',p_lead->>'nome',v_tel,'Tag adicionada: '||v_tag);
      else
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','alerta',p_lead->>'nome',v_tel,'Tag ja existia: '||v_tag);
      end if;
    elsif act_name='remove-tag-action' then
      v_tag := public.motor_subst(coalesce(ao->>'tag',''), p_lead);
      if v_lead_id is not null and v_tag<>'' then
        update leads set tags = coalesce((select jsonb_agg(e) from jsonb_array_elements(case when jsonb_typeof(tags)='array' then tags else '[]'::jsonb end) e where lower(e->>'name')<>lower(v_tag)),'[]'::jsonb) where id=v_lead_id;
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','ok',p_lead->>'nome',v_tel,'Tag removida: '||v_tag);
      else
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','alerta',p_lead->>'nome',v_tel,'Remover tag: lead/tag ausente');
      end if;
    elsif act_name='start-another-automation-action' then
      select id into v_target from automacoes where nome = ao->>'automacao' limit 1;
      if v_target is null then
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','erro',p_lead->>'nome',v_tel,'Iniciar: automacao nao encontrada ('||coalesce(ao->>'automacao','?')||')');
      elsif p_depth >= 3 then
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','alerta',p_lead->>'nome',v_tel,'Iniciar: limite de encadeamento atingido');
      else
        perform motor_rodar(v_target, p_lead, null, p_depth+1);
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','ok',p_lead->>'nome',v_tel,'Iniciou automacao: '||(ao->>'automacao'));
      end if;
    elsif act_name='send-notification-action' then
      declare
        v_cor bigint; v_titulo text; v_detalhe text; v_chave text; v_gravou int; v_tipo text;
      begin
        v_titulo  := motor_subst(coalesce(nullif(btrim(coalesce(ao->>'titulo','')),''),'Aviso da automacao'), p_lead);
        v_detalhe := motor_subst(coalesce(ao->>'detalhe',''), p_lead);
        if v_lead_id is not null then select corretor_id into v_cor from leads where id = v_lead_id; end if;
        v_chave := 'automacao:'||p_auto||':'||p_bloco||':'||coalesce(v_lead_id::text,'0');

        v_tipo := coalesce(nullif(ao->>'tipo',''), 'acao_vencida');
        if not exists (select 1 from ncrm_notificacao_tipos_ativos t where t.tipo = v_tipo) then
          insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)
          values(p_auto,p_nome,p_bloco,'acao','alerta',p_lead->>'nome',v_tel,
            'Aviso NAO enviado: tipo "'||v_tipo||'" nao esta ligado. Tipos aceitos: '||
            coalesce((select string_agg(t.tipo, ', ' order by t.tipo) from ncrm_notificacao_tipos_ativos t),'nenhum'));
        else
        insert into ncrm_notificacao(chave, tipo, publico, prioridade, titulo, detalhe, negocio_id, corretor_id)
        values (v_chave,
                v_tipo,
                coalesce(nullif(ao->>'publico',''), 'corretor'),
                coalesce(nullif(ao->>'prioridade','')::smallint, 3::smallint),
                v_titulo, nullif(v_detalhe,''), v_negocio_id, v_cor)
        on conflict do nothing;

        get diagnostics v_gravou = row_count;
        if v_gravou > 0 then
          insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)
          values(p_auto,p_nome,p_bloco,'acao','ok',p_lead->>'nome',v_tel,
            'Aviso enviado ao corretor: '||left(v_titulo,80));
        else
          insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)
          values(p_auto,p_nome,p_bloco,'acao','alerta',p_lead->>'nome',v_tel,
            'Aviso NAO chegou: o tipo "'||coalesce(nullif(ao->>'tipo',''),'automacao')||
            '" nao esta na lista de tipos ativos de notificacao');
        end if;
        end if;
      exception when others then
        insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe)
        values(p_auto,p_nome,p_bloco,'acao','erro',p_lead->>'nome',v_tel,
          'Nao consegui avisar: '||left(coalesce(SQLERRM,''),120));
      end;

    elsif act_name='set-lead-momento-action' then
      perform motor_momento_lead(p_auto, p_nome, p_bloco, p_lead, v_lead_id, v_negocio_id, ao->>'momento', ao->>'observacao');
    else
      insert into motor_execucoes(automacao_id,automacao_nome,bloco_id,evento,status,lead_nome,lead_telefone,detalhe) values(p_auto,p_nome,p_bloco,'acao','alerta',p_lead->>'nome',v_tel,'Acao (integracao pendente): '||coalesce(act_name,'?'));
    end if;
  end loop;
  return jsonb_build_object('lead_id',v_lead_id,'negocio_id',v_negocio_id);
