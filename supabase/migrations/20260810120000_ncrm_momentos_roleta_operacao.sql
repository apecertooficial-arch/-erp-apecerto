CREATE OR REPLACE FUNCTION public.ncrm_primeira_abordagem_prazo(p_agora timestamptz DEFAULT now())
RETURNS timestamptz LANGUAGE plpgsql STABLE SET search_path='' AS $fn$
DECLARE cfg public.ncrm_operacao_config%ROWTYPE; v_local timestamp; v_alvo timestamp;
BEGIN
  SELECT * INTO cfg FROM public.ncrm_operacao_config WHERE id=true;
  v_local:=p_agora AT TIME ZONE cfg.timezone;
  IF v_local::time>=cfg.horario_oficial_inicio AND v_local::time<cfg.horario_oficial_fim THEN
    RETURN p_agora+make_interval(mins=>cfg.primeira_abordagem_min);
  END IF;
  v_alvo:=CASE WHEN v_local::time<cfg.horario_oficial_inicio
    THEN v_local::date+cfg.horario_oficial_inicio
    ELSE (v_local::date+1)+cfg.horario_oficial_inicio END;
  RETURN v_alvo AT TIME ZONE cfg.timezone;
END $fn$;
