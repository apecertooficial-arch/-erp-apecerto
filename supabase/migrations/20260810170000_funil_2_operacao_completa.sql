CREATE OR REPLACE FUNCTION public.f2_configurar_etapa(
  p_codigo text,p_rotulo text,p_ajuda text,p_ordem integer,p_ativo boolean DEFAULT true
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $fn$
DECLARE v_uid uuid:=(SELECT auth.uid()); v_antes jsonb; v_codigo text:=lower(btrim(p_codigo));
BEGIN
  IF v_uid IS NULL OR public.f2_admin() IS NOT TRUE THEN RETURN jsonb_build_object('ok',false,'erro','sem_permissao'); END IF;
  IF v_codigo !~ '^[a-z0-9_]{3,40}$' OR char_length(btrim(p_rotulo)) NOT BETWEEN 2 AND 60 OR p_ordem NOT BETWEEN 1 AND 50
    THEN RETURN jsonb_build_object('ok',false,'erro','dados_invalidos'); END IF;
  SELECT to_jsonb(e) INTO v_antes FROM public.f2_etapa_config e WHERE codigo=v_codigo;
  IF p_ativo IS FALSE AND (EXISTS(SELECT 1 FROM public.f2_lead WHERE etapa=v_codigo) OR EXISTS(SELECT 1 FROM public.f2_momento_config WHERE etapa=v_codigo AND ativo))
    THEN RETURN jsonb_build_object('ok',false,'erro','etapa_em_uso'); END IF;
  INSERT INTO public.f2_etapa_config(codigo,ordem,rotulo,ajuda,ativo,atualizado_em)
  VALUES(v_codigo,p_ordem,btrim(p_rotulo),left(COALESCE(p_ajuda,''),240),COALESCE(p_ativo,true),now())
  ON CONFLICT(codigo) DO UPDATE SET ordem=EXCLUDED.ordem,rotulo=EXCLUDED.rotulo,ajuda=EXCLUDED.ajuda,ativo=EXCLUDED.ativo,atualizado_em=now();
  INSERT INTO public.f2_config_audit(tipo,chave,acao,antes,depois,criado_por)
  SELECT 'etapa',v_codigo,CASE WHEN v_antes IS NULL THEN 'criar' ELSE 'atualizar' END,v_antes,to_jsonb(e),v_uid FROM public.f2_etapa_config e WHERE codigo=v_codigo;
  RETURN jsonb_build_object('ok',true,'codigo',v_codigo);
EXCEPTION WHEN unique_violation THEN RETURN jsonb_build_object('ok',false,'erro','ordem_em_uso');
END;$fn$;

CREATE OR REPLACE FUNCTION public.f2_configurar_momento(
  p_codigo text,p_etapa text,p_rotulo text,p_descricao text,p_acao_rotulo text,
  p_prazo_minutos integer,p_ordem integer,p_exige_dapi boolean DEFAULT false,p_ativo boolean DEFAULT true
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $fn$
DECLARE v_uid uuid:=(SELECT auth.uid()); v_antes jsonb; v_codigo text:=upper(btrim(p_codigo));
BEGIN
  IF v_uid IS NULL OR public.f2_admin() IS NOT TRUE THEN RETURN jsonb_build_object('ok',false,'erro','sem_permissao'); END IF;
  IF v_codigo !~ '^[A-Z0-9_]{3,50}$' OR NOT EXISTS(SELECT 1 FROM public.f2_etapa_config WHERE codigo=p_etapa AND ativo)
     OR char_length(btrim(p_rotulo)) NOT BETWEEN 2 AND 80 OR char_length(btrim(p_acao_rotulo)) NOT BETWEEN 2 AND 120
     OR p_prazo_minutos NOT BETWEEN 1 AND 43200 OR p_ordem NOT BETWEEN 1 AND 100
    THEN RETURN jsonb_build_object('ok',false,'erro','dados_invalidos'); END IF;
  SELECT to_jsonb(m) INTO v_antes FROM public.f2_momento_config m WHERE codigo=v_codigo;
  IF p_ativo IS FALSE AND EXISTS(SELECT 1 FROM public.f2_lead WHERE momento_codigo=v_codigo)
    THEN RETURN jsonb_build_object('ok',false,'erro','momento_em_uso'); END IF;
  INSERT INTO public.f2_momento_config(codigo,etapa,ordem,rotulo,descricao,acao_codigo,acao_rotulo,prazo_minutos,prazo_rotulo,exige_dapi,ativo,atualizado_em)
  VALUES(v_codigo,p_etapa,p_ordem,btrim(p_rotulo),left(btrim(p_descricao),300),v_codigo,btrim(p_acao_rotulo),p_prazo_minutos,
    CASE WHEN p_prazo_minutos%1440=0 THEN (p_prazo_minutos/1440)||' dia(s)' WHEN p_prazo_minutos%60=0 THEN (p_prazo_minutos/60)||' hora(s)' ELSE p_prazo_minutos||' minutos' END,
    COALESCE(p_exige_dapi,false),COALESCE(p_ativo,true),now())
  ON CONFLICT(codigo) DO UPDATE SET etapa=EXCLUDED.etapa,ordem=EXCLUDED.ordem,rotulo=EXCLUDED.rotulo,
    descricao=EXCLUDED.descricao,acao_codigo=EXCLUDED.acao_codigo,acao_rotulo=EXCLUDED.acao_rotulo,
    prazo_minutos=EXCLUDED.prazo_minutos,prazo_rotulo=EXCLUDED.prazo_rotulo,exige_dapi=EXCLUDED.exige_dapi,ativo=EXCLUDED.ativo,atualizado_em=now();
  INSERT INTO public.f2_config_audit(tipo,chave,acao,antes,depois,criado_por)
  SELECT 'momento',v_codigo,CASE WHEN v_antes IS NULL THEN 'criar' ELSE 'atualizar' END,v_antes,to_jsonb(m),v_uid FROM public.f2_momento_config m WHERE codigo=v_codigo;
  RETURN jsonb_build_object('ok',true,'codigo',v_codigo);
EXCEPTION WHEN unique_violation THEN RETURN jsonb_build_object('ok',false,'erro','ordem_em_uso');
END;$fn$;

CREATE OR REPLACE FUNCTION public.f2_salvar_visita(
  p_id uuid,p_lead_id uuid,p_inicio_em timestamptz,p_imovel text,p_status text DEFAULT 'agendada',p_observacao text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $fn$
DECLARE v_uid uuid:=(SELECT auth.uid()); v_id uuid:=COALESCE(p_id,gen_random_uuid());
BEGIN
  IF v_uid IS NULL OR public.f2_admin() IS NOT TRUE THEN RETURN jsonb_build_object('ok',false,'erro','sem_permissao'); END IF;
  IF NOT EXISTS(SELECT 1 FROM public.f2_lead WHERE id=p_lead_id) OR p_status NOT IN ('agendada','confirmada','realizada','cancelada','nao_compareceu')
    OR p_inicio_em IS NULL OR char_length(btrim(p_imovel)) NOT BETWEEN 2 AND 120 THEN RETURN jsonb_build_object('ok',false,'erro','dados_invalidos'); END IF;
  INSERT INTO public.f2_visita(id,funil_lead_id,inicio_em,imovel,status,observacao,atualizado_por)
  VALUES(v_id,p_lead_id,p_inicio_em,btrim(p_imovel),p_status,left(p_observacao,500),v_uid)
  ON CONFLICT(id) DO UPDATE SET inicio_em=EXCLUDED.inicio_em,imovel=EXCLUDED.imovel,status=EXCLUDED.status,observacao=EXCLUDED.observacao,atualizado_em=now(),atualizado_por=v_uid
  WHERE public.f2_visita.funil_lead_id=p_lead_id;
  INSERT INTO public.f2_config_audit(tipo,chave,acao,depois,criado_por) SELECT 'visita',v_id::text,'salvar',to_jsonb(v),v_uid FROM public.f2_visita v WHERE id=v_id;
  RETURN jsonb_build_object('ok',true,'id',v_id);
END;$fn$;

CREATE OR REPLACE FUNCTION public.f2_salvar_negociacao(
  p_id uuid,p_lead_id uuid,p_titulo text,p_etapa text DEFAULT 'qualificacao',p_valor numeric DEFAULT NULL,p_observacao text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $fn$
DECLARE v_uid uuid:=(SELECT auth.uid()); v_id uuid:=COALESCE(p_id,gen_random_uuid());
BEGIN
  IF v_uid IS NULL OR public.f2_admin() IS NOT TRUE THEN RETURN jsonb_build_object('ok',false,'erro','sem_permissao'); END IF;
  IF NOT EXISTS(SELECT 1 FROM public.f2_lead WHERE id=p_lead_id) OR p_etapa NOT IN ('qualificacao','simulacao','proposta','documentacao','contrato','venda','perdida')
    OR char_length(btrim(p_titulo)) NOT BETWEEN 2 AND 120 OR (p_valor IS NOT NULL AND p_valor<0) THEN RETURN jsonb_build_object('ok',false,'erro','dados_invalidos'); END IF;
  INSERT INTO public.f2_negociacao(id,funil_lead_id,titulo,etapa,valor,observacao,atualizado_por)
  VALUES(v_id,p_lead_id,btrim(p_titulo),p_etapa,p_valor,left(p_observacao,500),v_uid)
  ON CONFLICT(id) DO UPDATE SET titulo=EXCLUDED.titulo,etapa=EXCLUDED.etapa,valor=EXCLUDED.valor,observacao=EXCLUDED.observacao,atualizado_em=now(),atualizado_por=v_uid
  WHERE public.f2_negociacao.funil_lead_id=p_lead_id;
  INSERT INTO public.f2_config_audit(tipo,chave,acao,depois,criado_por) SELECT 'negociacao',v_id::text,'salvar',to_jsonb(n),v_uid FROM public.f2_negociacao n WHERE id=v_id;
  RETURN jsonb_build_object('ok',true,'id',v_id);
END;$fn$;

CREATE OR REPLACE FUNCTION public.f2_listar_aquario()
RETURNS TABLE(negocio_id bigint,nome text,corretor_nome text,momento text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO '' AS $fn$
  SELECT n.id,l.nome,c.nome,e.momento_codigo
  FROM public.ncrm_estado e
  JOIN public.negocios n ON n.id=e.negocio_id
  JOIN public.leads l ON l.id=n.lead_id
  LEFT JOIN public.corretores c ON c.id=n.corretor_id
  WHERE public.f2_admin() AND NOT EXISTS(SELECT 1 FROM public.f2_lead f WHERE f.origem_negocio_id=n.id)
  ORDER BY e.ultima_interacao_em DESC NULLS LAST,n.id DESC LIMIT 20;
$fn$;

CREATE OR REPLACE FUNCTION public.f2_pescar_negocio(p_negocio_id bigint,p_substituir_id uuid DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $fn$
DECLARE v_uid uuid:=(SELECT auth.uid()); v_novo uuid;
BEGIN
  IF v_uid IS NULL OR public.f2_admin() IS NOT TRUE THEN RETURN jsonb_build_object('ok',false,'erro','sem_permissao'); END IF;
  IF EXISTS(SELECT 1 FROM public.f2_lead WHERE origem_negocio_id=p_negocio_id) THEN RETURN jsonb_build_object('ok',false,'erro','ja_esta_no_funil'); END IF;
  IF (SELECT count(*) FROM public.f2_lead)>=2 AND p_substituir_id IS NULL THEN RETURN jsonb_build_object('ok',false,'erro','escolha_copia_para_substituir'); END IF;
  IF p_substituir_id IS NOT NULL THEN
    IF NOT EXISTS(SELECT 1 FROM public.f2_lead WHERE id=p_substituir_id) THEN RETURN jsonb_build_object('ok',false,'erro','copia_invalida'); END IF;
    DELETE FROM public.f2_lead WHERE id=p_substituir_id;
  END IF;
  v_novo:=public.f2_importar_negocio(p_negocio_id);
  INSERT INTO public.f2_config_audit(tipo,chave,acao,depois,criado_por) VALUES('pesca',p_negocio_id::text,'substituir_copia',jsonb_build_object('novo_id',v_novo,'substituido',p_substituir_id),v_uid);
  RETURN jsonb_build_object('ok',true,'id',v_novo);
EXCEPTION WHEN OTHERS THEN RAISE;
END;$fn$;

