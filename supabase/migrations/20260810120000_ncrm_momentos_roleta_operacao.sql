GRANT EXECUTE ON FUNCTION public.ncrm_sara_aplicar_proxima_acao(bigint,bigint,text) TO authenticated;

-- O runner da Sara organiza o CRM automaticamente, mas apenas dentro do
-- catálogo fechado. Isto NÃO executa a obrigação: não envia mensagem, não
-- agenda visita e não cria proposta/venda. Só grava Momento + Ação + Prazo.
CREATE OR REPLACE FUNCTION public.ncrm_sara_aplicar_conduta_automatica(
  p_negocio_id bigint,p_analise_id bigint,p_momento_codigo text,p_acao_codigo text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_a public.ncrm_sara_analise%ROWTYPE; v_e public.ncrm_estado%ROWTYPE;
        v_m public.ncrm_momento_padrao%ROWTYPE; v_cat public.ncrm_acao_padrao%ROWTYPE;
        v_momento text:=p_momento_codigo; v_acao text:=p_acao_codigo;
        v_lead bigint; v_corretor bigint; v_prazo timestamptz;
BEGIN
  IF coalesce(auth.role(),'')<>'service_role' THEN
    RETURN jsonb_build_object('ok',false,'erro','somente_servico'); END IF;
  IF NOT EXISTS(SELECT 1 FROM public.ncrm_operacao_config WHERE id=true AND sara_organiza_ativa) THEN
    RETURN jsonb_build_object('ok',false,'erro','organizacao_desligada'); END IF;
  SELECT * INTO v_a FROM public.ncrm_sara_analise
   WHERE id=p_analise_id AND negocio_id=p_negocio_id;
  IF v_a.id IS NULL THEN RETURN jsonb_build_object('ok',false,'erro','analise_inexistente'); END IF;
  IF v_a.analisado_em<now()-interval '30 minutes' THEN
    RETURN jsonb_build_object('ok',false,'erro','analise_desatualizada'); END IF;
  IF coalesce(v_a.confianca,0)<.75 THEN
    RETURN jsonb_build_object('ok',false,'erro','confianca_insuficiente'); END IF;
  IF coalesce(jsonb_array_length(v_a.evidencias),0)=0 THEN
    RETURN jsonb_build_object('ok',false,'erro','analise_sem_base'); END IF;

  SELECT * INTO v_e FROM public.ncrm_estado WHERE negocio_id=p_negocio_id FOR UPDATE;
  IF v_e.negocio_id IS NULL OR v_e.saida IS NOT NULL THEN
    RETURN jsonb_build_object('ok',false,'erro','estado_indisponivel'); END IF;
  IF v_a.etapa_atual IS DISTINCT FROM v_e.etapa THEN
    RETURN jsonb_build_object('ok',false,'erro','estado_mudou'); END IF;
  IF v_e.ultima_decisao_humana_em IS NOT NULL AND v_e.ultima_decisao_humana_em>v_a.analisado_em THEN
    RETURN jsonb_build_object('ok',false,'erro','acao_humana_mais_recente'); END IF;

  -- Fatos inequívocos vencem interpretação: lead novo, ausência total de
  -- resposta e cliente aguardando o corretor têm uma única conduta possível.
  IF v_e.etapa='novo' THEN
    v_momento:='PRIMEIRA_ABORDAGEM'; v_acao:='PRIMEIRA_ABORDAGEM';
  ELSIF v_e.etapa='tentando_contato' AND NOT coalesce(v_e.respondeu,false) THEN
    v_momento:='CADENCIA_SEM_RESPOSTA'; v_acao:='ENVIAR_CADENCIA';
  ELSIF coalesce(v_e.resposta_pendente,false) THEN
    v_momento:='CONVERSANDO_QUALIFICANDO'; v_acao:='RESPONDER_E_QUALIFICAR';
  END IF;
  SELECT * INTO v_m FROM public.ncrm_momento_padrao
   WHERE codigo=v_momento AND ativo AND acao_codigo=v_acao;
  SELECT * INTO v_cat FROM public.ncrm_acao_padrao WHERE codigo=v_acao AND ativa;
  IF v_m.codigo IS NULL OR v_cat.codigo IS NULL THEN
    RETURN jsonb_build_object('ok',false,'erro','conduta_fora_do_catalogo'); END IF;
  IF EXISTS(SELECT 1 FROM public.ncrm_evento
    WHERE idempotency_key=concat('sara:auto:',p_analise_id)) THEN
    RETURN jsonb_build_object('ok',true,'ja_aplicado',true); END IF;

  v_prazo:=CASE
    WHEN v_m.codigo='RETORNO_PROGRAMADO' AND v_a.prazo_sugerido>now()
      AND v_a.prazo_sugerido<=now()+interval '5 days' THEN v_a.prazo_sugerido
    WHEN v_m.codigo='VISITA_AGENDADA' AND v_e.proxima_acao_em>now() THEN v_e.proxima_acao_em
    ELSE now()+make_interval(mins=>v_m.sla_min) END;
  SELECT lead_id,corretor_id INTO v_lead,v_corretor FROM public.negocios WHERE id=p_negocio_id;
  UPDATE public.ncrm_estado SET etapa=v_m.etapa,momento_codigo=v_m.codigo,
    proxima_acao_tipo=v_cat.proxima_acao_tipo,proxima_acao_titulo=v_cat.rotulo,
    proxima_acao_em=v_prazo,proxima_acao_motivo=left(coalesce(nullif(btrim(v_a.justificativa),''),v_m.objetivo),400),
    proxima_acao_origem='sara',origem_ultima='sara',versao=v_e.versao+1,
    atualizado_em=now(),atualizado_por=NULL
  WHERE negocio_id=p_negocio_id AND versao=v_e.versao;
  IF NOT FOUND THEN RETURN jsonb_build_object('ok',false,'erro','conflito_versao'); END IF;
  INSERT INTO public.ncrm_evento(negocio_id,lead_id,corretor_id_no_evento,workflow_config_id,
    tipo,resultado,payload,origem,executado_por,idempotency_key,estado_versao_antes,estado_versao_apos)
  VALUES(p_negocio_id,v_lead,v_corretor,v_e.workflow_config_id,'classificacao_sara',v_acao,
    jsonb_build_object('analise_id',p_analise_id,'momento_codigo',v_m.codigo,'prazo',v_prazo,
      'automatico',true,'executou_acao_comercial',false),
    'sara',NULL,concat('sara:auto:',p_analise_id),v_e.versao,v_e.versao+1);
  RETURN jsonb_build_object('ok',true,'aplicado',true,'momento_codigo',v_m.codigo,
    'acao_codigo',v_acao,'prazo',v_prazo,'versao',v_e.versao+1);
END $fn$;
REVOKE ALL ON FUNCTION public.ncrm_sara_aplicar_conduta_automatica(bigint,bigint,text,text)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.ncrm_sara_aplicar_conduta_automatica(bigint,bigint,text,text)
  TO service_role;

COMMIT;
