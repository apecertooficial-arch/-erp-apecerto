-- Regra central: estágio e momento determinam uma única conduta.
CREATE OR REPLACE FUNCTION public.ncrm_conduta_oficial_v4(
  p_etapa text,p_momento_codigo text,p_respondeu boolean,p_resposta_pendente boolean,
  p_tentativas integer,p_proxima_em timestamptz
) RETURNS jsonb LANGUAGE sql STABLE SET search_path='' AS $fn$
  WITH escolhido AS (
    SELECT m.* FROM public.ncrm_momento_padrao m
    WHERE m.ativo AND m.codigo = CASE
      WHEN p_etapa='novo' THEN 'PRIMEIRA_ABORDAGEM'
      WHEN p_etapa='tentando_contato' AND NOT coalesce(p_respondeu,false) THEN 'CADENCIA_SEM_RESPOSTA'
      WHEN p_momento_codigo IS NOT NULL THEN p_momento_codigo
      WHEN p_etapa='em_acompanhamento' THEN 'DECISAO_POS_VISITA'
      ELSE 'CONVERSANDO_QUALIFICANDO' END
    LIMIT 1
  )
  SELECT jsonb_build_object(
    'etapa',e.etapa,'momento_codigo',e.codigo,'momento',e.rotulo,'momento_ordem',e.ordem,
    'acao_codigo',CASE WHEN coalesce(p_resposta_pendente,false) THEN 'RESPONDER_E_QUALIFICAR' ELSE e.acao_codigo END,
    'acao',CASE
      WHEN e.codigo='CADENCIA_SEM_RESPOSTA' THEN concat('Enviar cadência ',LEAST(GREATEST(coalesce(p_tentativas,0)+1,1),5),' de 5')
      WHEN coalesce(p_resposta_pendente,false) THEN 'Responder e qualificar'
      ELSE a.rotulo END,
    'objetivo',CASE WHEN coalesce(p_resposta_pendente,false) THEN 'Responder o cliente e manter a conversa avançando.' ELSE a.objetivo END,
    'prazo',p_proxima_em,'sla_min',CASE WHEN coalesce(p_resposta_pendente,false) THEN 15 ELSE e.sla_min END,
    'ajuda',e.ajuda
  )
  FROM escolhido e
  JOIN public.ncrm_acao_padrao a ON a.codigo=CASE WHEN coalesce(p_resposta_pendente,false) THEN 'RESPONDER_E_QUALIFICAR' ELSE e.acao_codigo END;
$fn$;
REVOKE ALL ON FUNCTION public.ncrm_conduta_oficial_v4(text,text,boolean,boolean,integer,timestamptz)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.ncrm_conduta_oficial_v4(text,text,boolean,boolean,integer,timestamptz)
  TO service_role;

-- Atualização manual por menu suspenso. Etapa é derivada do momento escolhido.
CREATE OR REPLACE FUNCTION public.ncrm_atualizar_momento(
  p_negocio_id bigint,p_versao integer,p_momento_codigo text,p_observacao text DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_uid uuid:=auth.uid(); v_m public.ncrm_momento_padrao%ROWTYPE;
        v_e public.ncrm_estado%ROWTYPE; v_lead bigint; v_corretor bigint; v_prazo timestamptz;
BEGIN
  IF v_uid IS NULL THEN RETURN jsonb_build_object('ok',false,'erro','nao_autenticado'); END IF;
  IF ncrm_private.pode_operar_negocio(p_negocio_id) IS NOT TRUE THEN
    RETURN jsonb_build_object('ok',false,'erro','sem_permissao'); END IF;
  SELECT * INTO v_m FROM public.ncrm_momento_padrao WHERE codigo=p_momento_codigo AND ativo;
  IF v_m.codigo IS NULL THEN RETURN jsonb_build_object('ok',false,'erro','momento_invalido'); END IF;
  SELECT * INTO v_e FROM public.ncrm_estado WHERE negocio_id=p_negocio_id FOR UPDATE;
  IF v_e.negocio_id IS NULL THEN RETURN jsonb_build_object('ok',false,'erro','estado_inexistente'); END IF;
  IF v_e.saida IS NOT NULL THEN RETURN jsonb_build_object('ok',false,'erro','estado_em_saida'); END IF;
  IF v_e.versao<>p_versao THEN RETURN jsonb_build_object('ok',false,'erro','versao_conflito'); END IF;
  SELECT lead_id,corretor_id INTO v_lead,v_corretor FROM public.negocios WHERE id=p_negocio_id;
  v_prazo:=now()+make_interval(mins=>v_m.sla_min);
  UPDATE public.ncrm_estado SET etapa=v_m.etapa,momento_codigo=v_m.codigo,
    proxima_acao_tipo=(SELECT proxima_acao_tipo FROM public.ncrm_acao_padrao WHERE codigo=v_m.acao_codigo),
    proxima_acao_titulo=(SELECT rotulo FROM public.ncrm_acao_padrao WHERE codigo=v_m.acao_codigo),
    proxima_acao_em=v_prazo,proxima_acao_motivo=coalesce(nullif(btrim(p_observacao),''),v_m.objetivo),
    proxima_acao_origem='corretor',versao=v_e.versao+1,atualizado_em=now(),atualizado_por=v_uid,
    origem_ultima='usuario',ultima_decisao_humana_em=now()
  WHERE negocio_id=p_negocio_id AND versao=v_e.versao;
  INSERT INTO public.ncrm_evento(negocio_id,lead_id,corretor_id_no_evento,workflow_config_id,
    tipo,resultado,payload,origem,executado_por,idempotency_key,estado_versao_antes,estado_versao_apos)
  VALUES(p_negocio_id,v_lead,v_corretor,v_e.workflow_config_id,'correcao_manual',v_m.codigo,
    jsonb_build_object('etapa_anterior',v_e.etapa,'momento_anterior',v_e.momento_codigo,'observacao',p_observacao),
    'usuario',v_uid,concat('momento:',p_negocio_id,':',v_e.versao+1),v_e.versao,v_e.versao+1);
  RETURN jsonb_build_object('ok',true,'etapa',v_m.etapa,'momento_codigo',v_m.codigo,
    'momento',v_m.rotulo,'acao_codigo',v_m.acao_codigo,'prazo',v_prazo,'versao',v_e.versao+1);
END $fn$;
REVOKE ALL ON FUNCTION public.ncrm_atualizar_momento(bigint,integer,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.ncrm_atualizar_momento(bigint,integer,text,text) TO authenticated;

-- ---------------------------------------------------------------------------
-- 2.1. Uma visita é um evento paralelo, não uma saída do funil de atendimento
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.ncrm_agendar_visita_e_encaminhar(
  p_negocio_id bigint,p_versao integer,p_lead_id bigint,p_data date,p_hora_inicio text,
  p_empreendimento_id uuid,p_produto text,p_com_gerente boolean,p_gerente_id bigint,p_idem text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_uid uuid:=auth.uid(); v_lead bigint; v_corretor bigint; v_antes int; v_cfg bigint;
        v_nome text; v_visita uuid; v_inicio timestamptz; v_prazo timestamptz;
BEGIN
  PERFORM ncrm_private.assert_idem(p_idem);
  IF v_uid IS NULL THEN RETURN jsonb_build_object('ok',false,'erro','nao_autenticado'); END IF;
  SELECT n.lead_id,n.corretor_id INTO v_lead,v_corretor FROM public.negocios n WHERE n.id=p_negocio_id;
  IF NOT FOUND THEN RETURN jsonb_build_object('ok',false,'erro','negocio_inexistente'); END IF;
  IF ncrm_private.pode_operar_negocio(p_negocio_id) IS NOT TRUE THEN RETURN jsonb_build_object('ok',false,'erro','sem_permissao'); END IF;
  IF p_lead_id IS NULL OR p_lead_id<>v_lead THEN RETURN jsonb_build_object('ok',false,'erro','lead_incoerente'); END IF;
  IF p_data IS NULL OR p_hora_inicio IS NULL OR btrim(p_hora_inicio)='' THEN RETURN jsonb_build_object('ok',false,'erro','data_hora_obrigatorias'); END IF;
  v_inicio:=(p_data+p_hora_inicio::time) AT TIME ZONE 'America/Sao_Paulo';
  IF v_inicio<now() THEN RETURN jsonb_build_object('ok',false,'erro','data_no_passado'); END IF;
  IF EXISTS(SELECT 1 FROM public.ncrm_evento WHERE idempotency_key=p_idem) THEN RETURN jsonb_build_object('ok',true,'ja_processado',true); END IF;
  SELECT versao,workflow_config_id INTO v_antes,v_cfg FROM public.ncrm_estado WHERE negocio_id=p_negocio_id AND saida IS NULL FOR UPDATE;
  IF NOT FOUND THEN RETURN jsonb_build_object('ok',false,'erro','estado_indisponivel'); END IF;
  IF p_versao<>v_antes THEN RETURN jsonb_build_object('ok',false,'erro','versao_conflito'); END IF;
  SELECT nome INTO v_nome FROM public.leads WHERE id=v_lead;
  INSERT INTO public.visitas(created_by,lead_id,negocio_id,corretor_id,cliente_nome,empreendimento_id,produto,
    data,hora_inicio,com_gerente,gerente_id,status)
  VALUES(v_uid,v_lead,p_negocio_id,v_corretor,v_nome,p_empreendimento_id,p_produto,p_data,p_hora_inicio,
    coalesce(p_com_gerente,false),p_gerente_id,'agendada') RETURNING id INTO v_visita;
  v_prazo:=greatest(now()+interval '1 minute',v_inicio-interval '24 hours');
  UPDATE public.ncrm_estado SET etapa='em_atendimento',momento_codigo='VISITA_AGENDADA',
    saida=NULL,saida_em=NULL,visita_id=v_visita,proxima_acao_tipo='agendar_visita',
    proxima_acao_titulo='Confirmar a visita',proxima_acao_em=v_prazo,
    proxima_acao_motivo='confirmar presença 24 horas antes',proxima_acao_origem='visita',
    resposta_pendente=false,versao=v_antes+1,atualizado_em=now(),atualizado_por=v_uid,
    origem_ultima='usuario',ultima_decisao_humana_em=now()
  WHERE negocio_id=p_negocio_id AND versao=v_antes;
  INSERT INTO public.ncrm_evento(negocio_id,lead_id,corretor_id_no_evento,workflow_config_id,tipo,payload,
    origem,executado_por,idempotency_key,estado_versao_antes,estado_versao_apos)
  VALUES(p_negocio_id,v_lead,v_corretor,v_cfg,'visita_agendada',
    jsonb_build_object('visita_id',v_visita,'data',p_data,'hora',p_hora_inicio,'mesmo_atendimento',true),
    'usuario',v_uid,p_idem,v_antes,v_antes+1);
  RETURN jsonb_build_object('ok',true,'versao',v_antes+1,'visita_id',v_visita,
    'etapa','em_atendimento','momento_codigo','VISITA_AGENDADA');
EXCEPTION WHEN unique_violation THEN
  IF EXISTS(SELECT 1 FROM public.ncrm_evento WHERE idempotency_key=p_idem) THEN
    RETURN jsonb_build_object('ok',true,'ja_processado',true); ELSE RAISE; END IF;
END $fn$;

CREATE OR REPLACE FUNCTION public.ncrm_registrar_resultado_visita(
  p_visita_id uuid,p_negocio_id bigint,p_versao integer,p_resultado text,p_obs text,p_idem text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_uid uuid:=auth.uid(); v_lead bigint; v_corretor bigint; v_antes int; v_cfg bigint;
        v_etapa text; v_momento text; v_tipo text; v_titulo text; v_prazo timestamptz;
BEGIN
  PERFORM ncrm_private.assert_idem(p_idem);
  IF v_uid IS NULL THEN RETURN jsonb_build_object('ok',false,'erro','nao_autenticado'); END IF;
  IF p_resultado NOT IN('interessado','quer_outra_opcao','precisa_conversar','nao_gostou','nao_compareceu','remarcar','fara_proposta') THEN
    RETURN jsonb_build_object('ok',false,'erro','resultado_invalido'); END IF;
  SELECT n.lead_id,n.corretor_id INTO v_lead,v_corretor FROM public.negocios n WHERE n.id=p_negocio_id;
  IF NOT FOUND OR ncrm_private.pode_operar_negocio(p_negocio_id) IS NOT TRUE THEN RETURN jsonb_build_object('ok',false,'erro','sem_permissao'); END IF;
  IF NOT EXISTS(SELECT 1 FROM public.visitas WHERE id=p_visita_id AND negocio_id=p_negocio_id) THEN RETURN jsonb_build_object('ok',false,'erro','visita_invalida'); END IF;
  IF EXISTS(SELECT 1 FROM public.ncrm_evento WHERE idempotency_key=p_idem) THEN RETURN jsonb_build_object('ok',true,'ja_processado',true); END IF;
  SELECT versao,workflow_config_id INTO v_antes,v_cfg FROM public.ncrm_estado WHERE negocio_id=p_negocio_id AND saida IS NULL FOR UPDATE;
  IF NOT FOUND THEN RETURN jsonb_build_object('ok',false,'erro','estado_indisponivel'); END IF;
  IF p_versao<>v_antes THEN RETURN jsonb_build_object('ok',false,'erro','versao_conflito'); END IF;

  IF p_resultado IN('nao_compareceu','remarcar') THEN
    v_etapa:='em_atendimento'; v_momento:='TENTANDO_AGENDAMENTO'; v_tipo:='agendar_visita';
    v_titulo:='Agendar uma visita'; v_prazo:=now()+interval '12 hours';
  ELSIF p_resultado IN('quer_outra_opcao','nao_gostou') THEN
    v_etapa:='em_atendimento'; v_momento:='BUSCANDO_PRODUTO'; v_tipo:='enviar_opcoes';
    v_titulo:='Buscar e enviar imóveis'; v_prazo:=now()+interval '24 hours';
  ELSE
    v_etapa:='em_acompanhamento'; v_momento:='DECISAO_POS_VISITA'; v_tipo:='retornar_contato';
    v_titulo:='Definir o avanço pós-visita'; v_prazo:=now()+interval '24 hours';
  END IF;

  UPDATE public.visitas SET resultado=p_resultado,resultado_em=now(),resultado_por=v_uid,
    status=CASE WHEN p_resultado='nao_compareceu' THEN 'nao_compareceu' ELSE 'realizada' END
  WHERE id=p_visita_id;
  UPDATE public.ncrm_estado SET etapa=v_etapa,momento_codigo=v_momento,saida=NULL,saida_em=NULL,
    respondeu=true,resposta_pendente=false,proxima_acao_tipo=v_tipo,proxima_acao_titulo=v_titulo,
    proxima_acao_em=v_prazo,proxima_acao_motivo='resultado da visita: '||p_resultado,
    proxima_acao_origem='visita',ultima_interacao_em=now(),versao=v_antes+1,atualizado_em=now(),
    atualizado_por=v_uid,origem_ultima='usuario',ultima_decisao_humana_em=now()
  WHERE negocio_id=p_negocio_id AND versao=v_antes;
  INSERT INTO public.ncrm_evento(negocio_id,lead_id,corretor_id_no_evento,workflow_config_id,tipo,
    resultado,payload,origem,executado_por,idempotency_key,estado_versao_antes,estado_versao_apos)
  VALUES(p_negocio_id,v_lead,v_corretor,v_cfg,'acao_comercial',p_resultado,
    jsonb_build_object('visita_id',p_visita_id,'obs',p_obs,'origem','resultado_visita','momento_codigo',v_momento),
    'usuario',v_uid,p_idem,v_antes,v_antes+1);
  RETURN jsonb_build_object('ok',true,'versao',v_antes+1,'etapa',v_etapa,
    'momento_codigo',v_momento,'proxima_acao',v_titulo);
EXCEPTION WHEN unique_violation THEN
  IF EXISTS(SELECT 1 FROM public.ncrm_evento WHERE idempotency_key=p_idem) THEN
    RETURN jsonb_build_object('ok',true,'ja_processado',true); ELSE RAISE; END IF;
END $fn$;

-- ---------------------------------------------------------------------------
-- 3. Elegibilidade da roleta: presença + D-API + visitas + suspensão
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.ncrm_corretor_elegibilidade(
  p_corretor_id bigint,p_agora timestamptz DEFAULT now()
) RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $fn$
DECLARE c public.corretores%ROWTYPE; cfg public.ncrm_operacao_config%ROWTYPE;
        local_ts timestamp; local_d date; local_t time; atual boolean; compareceu boolean;
        conectado boolean; visita_pendente integer; suspenso_ate timestamptz;
BEGIN
  SELECT * INTO c FROM public.corretores WHERE id=p_corretor_id;
  IF c.id IS NULL OR coalesce(c.ativo,false) IS NOT TRUE THEN
    RETURN jsonb_build_object('elegivel',false,'motivo','corretor_inativo'); END IF;
  SELECT * INTO cfg FROM public.ncrm_operacao_config WHERE id=true;
  local_ts:=p_agora AT TIME ZONE cfg.timezone; local_d:=local_ts::date; local_t:=local_ts::time;
  conectado:=EXISTS(SELECT 1 FROM public.instancias i WHERE i.corretor_id=c.id
    AND coalesce(i.ativa,true) AND coalesce(i.conectada,false) AND i.status_dapi='connected');
  IF NOT conectado THEN RETURN jsonb_build_object('elegivel',false,'motivo','dapi_desconectada'); END IF;
  SELECT max(s.fim_em) INTO suspenso_ate FROM public.ncrm_corretor_suspensao s
    WHERE s.corretor_id=c.id AND s.revogada_em IS NULL AND s.inicio_em<=p_agora AND s.fim_em>p_agora;
  IF suspenso_ate IS NOT NULL THEN RETURN jsonb_build_object('elegivel',false,'motivo','suspenso','ate',suspenso_ate); END IF;

  SELECT count(*) INTO visita_pendente FROM public.visitas v
   WHERE v.corretor_id=c.id AND v.criado_em>=cfg.corte_feedback_visita
     AND v.status='realizada' AND v.resultado IS NULL
     AND (v.data+coalesce(nullif(v.hora_fim::text,''),nullif(v.hora_inicio::text,''),'18:00')::time) AT TIME ZONE cfg.timezone
           < p_agora-make_interval(mins=>cfg.feedback_visita_min);
  IF visita_pendente>0 THEN RETURN jsonb_build_object('elegivel',false,'motivo','feedback_visita_pendente','quantidade',visita_pendente); END IF;

  atual:=coalesce(c.no_escritorio,false) AND c.ultima_presenca IS NOT NULL
    AND c.ultima_presenca>p_agora-make_interval(mins=>cfg.presenca_ttl_min);
  compareceu:=EXISTS(SELECT 1 FROM public.corretor_presencas cp WHERE cp.corretor_id=c.id AND cp.dia=local_d);
  IF local_t>=cfg.horario_oficial_inicio AND local_t<cfg.horario_oficial_fim THEN
    IF NOT (coalesce(c.online,false) OR atual) THEN
      RETURN jsonb_build_object('elegivel',false,'motivo','presenca_nao_confirmada','periodo','oficial'); END IF;
    RETURN jsonb_build_object('elegivel',true,'motivo','ok','periodo','oficial');
  END IF;
  -- Fora do horário: quem ainda está no escritório recebe; depois que o último
  -- sai, os leads ficam disponíveis para quem compareceu no dia, sem aceite.
  IF EXISTS(SELECT 1 FROM public.corretores cx WHERE coalesce(cx.ativo,false)
      AND coalesce(cx.no_escritorio,false) AND cx.ultima_presenca>p_agora-make_interval(mins=>cfg.presenca_ttl_min)) THEN
    IF NOT atual THEN RETURN jsonb_build_object('elegivel',false,'motivo','fora_horario_nao_presente','periodo','remoto'); END IF;
    RETURN jsonb_build_object('elegivel',true,'motivo','presente_fora_horario','periodo','remoto');
  END IF;
  IF NOT compareceu THEN RETURN jsonb_build_object('elegivel',false,'motivo','nao_compareceu_no_dia','periodo','remoto'); END IF;
  RETURN jsonb_build_object('elegivel',true,'motivo','compareceu_no_dia','periodo','remoto','cobranca_5min',false);
END $fn$;
REVOKE ALL ON FUNCTION public.ncrm_corretor_elegibilidade(bigint,timestamptz) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.ncrm_corretor_elegibilidade(bigint,timestamptz) TO service_role;

