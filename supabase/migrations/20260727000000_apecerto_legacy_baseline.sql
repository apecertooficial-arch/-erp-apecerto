    ] LOOP
      IF to_regclass('public.' || v_table) IS NULL THEN
        RAISE EXCEPTION 'apecerto_baseline_drift: tabela public.% ausente em base existente', v_table;
      END IF;
    END LOOP;

    FOR v_col IN SELECT * FROM (VALUES
      ('id','uuid','NO'), ('nome','text','NO'), ('role','USER-DEFINED','NO'),
      ('ativo','boolean','NO'), ('created_at','timestamp with time zone','NO')
    ) AS required(column_name,data_type,is_nullable)
    LOOP
      IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns c
        WHERE c.table_schema='public' AND c.table_name='usuarios'
          AND c.column_name=v_col.column_name AND c.data_type=v_col.data_type
          AND c.is_nullable=v_col.is_nullable
      ) THEN
        RAISE EXCEPTION 'apecerto_baseline_drift: public.usuarios.% deve ser % NOT NULL',
          v_col.column_name,v_col.data_type;
      END IF;
    END LOOP;

    IF (SELECT udt_name FROM information_schema.columns
        WHERE table_schema='public' AND table_name='usuarios' AND column_name='role') <> 'user_role' THEN
      RAISE EXCEPTION 'apecerto_baseline_drift: public.usuarios.role deve usar public.user_role';
    END IF;
    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid
      JOIN pg_namespace n ON n.oid=t.relnamespace
      WHERE n.nspname='public' AND t.relname='usuarios' AND c.contype='p'
    ) THEN RAISE EXCEPTION 'apecerto_baseline_drift: public.usuarios sem chave primaria'; END IF;
    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid
      JOIN pg_namespace n ON n.oid=t.relnamespace
      WHERE n.nspname='public' AND t.relname='usuarios' AND c.contype='f'
        AND pg_get_constraintdef(c.oid) LIKE 'FOREIGN KEY (id) REFERENCES auth.users(id)%'
